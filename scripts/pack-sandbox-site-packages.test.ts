import { expect, test } from "bun:test";
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { packSandboxSitePackages } from "./pack-sandbox-site-packages";

test("isolated Site resolves the matching SDK, React and Codemode package closure", async () => {
  const root = await mkdtemp(join(tmpdir(), "opengeni-package-test-"));
  try {
    const archives = join(root, "archives");
    const project = join(root, "project");
    await mkdir(project);
    await packSandboxSitePackages(archives, archives);
    const manifest = JSON.stringify({ name: "site-test", private: true, type: "module" });
    await writeFile(join(project, "package.json"), manifest);
    const install = Bun.spawn(
      [
        "bun",
        "add",
        "--no-save",
        join(archives, "sdk.tgz"),
        join(archives, "react.tgz"),
        join(archives, "codemode.tgz"),
        "react",
        "react-dom",
      ],
      { cwd: project, stdout: "pipe", stderr: "pipe" },
    );
    const errors = await new Response(install.stderr).text();
    expect(await install.exited, errors).toBe(0);
    expect(await Bun.file(join(project, "package.json")).text()).toBe(manifest);
    const check = Bun.spawn(
      [
        "bun",
        "-e",
        `
      import {createOpenGeniSiteClient} from '@opengeni/sdk/site';
      import {SessionConversation} from '@opengeni/react/session-ui';
      import {createCodemodeSiteRequestHandler} from '@opengeni/codemode';
      const site=createOpenGeniSiteClient();
      if (!site.client || !site.workspaceId || typeof SessionConversation!=='function' || typeof createCodemodeSiteRequestHandler!=='function') throw Error('Missing deployment API');
      site.close();
    `,
      ],
      { cwd: project, stdout: "pipe", stderr: "pipe" },
    );
    const failure = await new Response(check.stderr).text();
    expect(await check.exited, failure).toBe(0);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}, 120_000);
