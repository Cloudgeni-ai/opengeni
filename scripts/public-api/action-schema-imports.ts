/** Build-time-only schema namespace discovery; never import this from the API. */
import * as contracts from "@opengeni/contracts";
import { z } from "zod";
import type { ActionCatalogEntry } from "../../apps/api/src/mcp/action-catalog-types";
import { ACTION_CATALOG } from "../../apps/api/src/mcp/action-catalog.gen";

export const ACTION_SCHEMA_IMPORTS_PATH = new URL(
  "../../apps/api/src/mcp/action-schema-imports.gen.ts",
  import.meta.url,
);

export function renderActionSchemaImports(entries: readonly ActionCatalogEntry[]): string {
  const namespace = contracts as Record<string, unknown>;
  const names = [...new Set(entries.flatMap((entry) => entry.request))]
    .filter((name) => namespace[name] instanceof z.ZodType)
    .sort();
  for (const name of names) {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name)) {
      throw new Error(`Invalid action schema export name: ${name}`);
    }
  }
  return `// Generated by scripts/public-api/action-catalog.ts. Do not edit.
// Named imports keep unrelated response and tool validators out of the API graph.
import { ${names.join(", ")} } from "@opengeni/contracts";

export const ACTION_REQUEST_SCHEMAS: Readonly<Record<string, unknown>> = {
${names.map((name) => `  ${name},`).join("\n")}
};
`;
}

if (import.meta.main && process.argv.includes("--write")) {
  await Bun.write(ACTION_SCHEMA_IMPORTS_PATH, renderActionSchemaImports(ACTION_CATALOG));
}
