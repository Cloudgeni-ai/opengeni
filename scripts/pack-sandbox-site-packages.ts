import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

/** Source packages are intentional: sandbox Bun builds TS/TSX directly. Never
 * copy stale dist output or mutate the repository's publish manifests. */
export async function packSandboxSitePackages(output: string, installPath: string) {
  const root = resolve(import.meta.dir, "..");
  const names = ["contracts", "tool-gateway", "sdk", "codemode", "react"];
  await mkdir(output, { recursive: true });
  const stage = await mkdtemp(join(tmpdir(), "opengeni-site-packages-"));
  try {
    for (const name of names) {
      const source = join(root, "packages", name);
      const target = join(stage, name);
      await mkdir(target);
      const manifest = JSON.parse(await readFile(join(source, "package.json"), "utf8"));
      delete manifest.scripts;
      delete manifest.devDependencies;
      manifest.files = name === "react" ? ["src", "styles"] : ["src"];
      for (const [dependency, version] of Object.entries(manifest.dependencies ?? {})) {
        if (typeof version === "string" && version.startsWith("workspace:")) {
          const sibling = dependency.replace("@opengeni/", "");
          if (!names.includes(sibling)) throw new Error(`Missing sandbox package: ${dependency}`);
          manifest.dependencies[dependency] = `file:${join(installPath, `${sibling}.tgz`)}`;
        }
      }
      await cp(join(source, "src"), join(target, "src"), { recursive: true });
      if (name === "react")
        await cp(join(source, "styles"), join(target, "styles"), { recursive: true });
      await writeFile(join(target, "package.json"), JSON.stringify(manifest, null, 2));
      const child = Bun.spawn(
        [
          "bun",
          "pm",
          "pack",
          "--ignore-scripts",
          "--quiet",
          "--filename",
          join(output, `${name}.tgz`),
        ],
        { cwd: target, stdout: "inherit", stderr: "inherit" },
      );
      if (await child.exited) throw new Error(`Packing ${name} failed`);
    }
  } finally {
    await rm(stage, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const output = resolve(process.argv[2] ?? ".opengeni/site-packages");
  await packSandboxSitePackages(output, process.argv[3] ?? "/opt/opengeni/site-packages");
}
