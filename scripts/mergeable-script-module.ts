/**
 * Render a bundled browser script as a TypeScript string constant that Git can
 * merge like source.
 *
 * A fully minified bundle is one line, so any two changes to it conflict, even
 * when they come from unrelated source edits: two queued PRs that each rebuild
 * the script can never both merge. Mangled names make it worse, because the
 * minifier reassigns them across the whole bundle on every change.
 *
 * So build with {@link MERGEABLE_MINIFY} (whitespace and syntax minified, names
 * kept), and this module cuts the script after every `;`, `{` and `}` and
 * before every `function` and `class`, about one piece per source statement,
 * each on its own line. The pieces join back into exactly the bundled bytes. A
 * source change then rewrites only the lines built from it, and changes to
 * different code merge cleanly.
 */
export const MERGEABLE_MINIFY = { whitespace: true, syntax: true, identifiers: false } as const;

/** Any cut is safe, even inside a string: the pieces are joined back unchanged. */
const PIECE_BOUNDARY = /(?<=[;{}])|(?=\b(?:function|class)\b)/u;

export function mergeableScriptModule(options: {
  generator: string;
  name: string;
  script: string;
}): string {
  const pieces = options.script.split(PIECE_BOUNDARY).filter((piece) => piece !== "");
  if (pieces.join("") !== options.script) throw new Error("Script pieces do not rejoin exactly");
  return (
    `// Generated by ${options.generator}. Do not edit.\n` +
    `export const ${options.name}: string = [\n` +
    pieces.map((piece) => `  ${JSON.stringify(piece)},\n`).join("") +
    `].join("");\n`
  );
}
