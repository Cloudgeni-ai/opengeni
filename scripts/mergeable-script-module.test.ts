import { describe, expect, test } from "bun:test";
import { mergeableScriptModule } from "./mergeable-script-module";

const script =
  '(()=>{var a="x;y{z}",b=1;function one(){return a}class Two{run(){if(b){b+=1}return one()}}' +
  "let three=()=>{for(let i=0;i<2;i++){b+=i}};function four(){three();return`t${b}`}" +
  'Object.defineProperty(globalThis,"four",{value:four});})();\n';

function render(text: string): string {
  return mergeableScriptModule({ generator: "test", name: "SCRIPT", script: text });
}

/** Evaluate the rendered module and return its constant. */
function evaluate(module: string): string {
  const body = module.replace(/^\/\/.*\n/u, "").replace("export const SCRIPT: string =", "return");
  return new Function(body)() as string;
}

/** Lines the two renders differ in, after their common first and last lines. */
function changedLines(before: string, after: string): number {
  const a = before.split("\n");
  const b = after.split("\n");
  let start = 0;
  while (start < a.length && start < b.length && a[start] === b[start]) start += 1;
  let end = 0;
  while (end < a.length - start && end < b.length - start && a.at(-1 - end) === b.at(-1 - end))
    end += 1;
  return Math.max(a.length, b.length) - start - end;
}

describe("mergeableScriptModule", () => {
  test("the lines join back into exactly the bundled script", () => {
    const module = render(script);
    expect(evaluate(module)).toBe(script);
    expect(module.split("\n").length).toBeGreaterThan(10);
    expect(module.startsWith("// Generated by test. Do not edit.\n")).toBe(true);
  });

  test("an edit changes only the lines built from it", () => {
    const base = render(script);
    const early = render(script.replace("return a}", "return a+a}"));
    const late = render(script.replace("return`t${b}`", "return`u${b}`"));
    expect(changedLines(base, early)).toBe(1);
    expect(changedLines(base, late)).toBe(1);
    // The two edits are far apart, so Git merges them like source.
    const earlyLine = base
      .split("\n")
      .findIndex((line, index) => line !== early.split("\n")[index]);
    const lateLine = base.split("\n").findIndex((line, index) => line !== late.split("\n")[index]);
    expect(lateLine - earlyLine).toBeGreaterThan(2);
  });

  test("strings that contain cut characters still join back unchanged", () => {
    const tricky = 'var s="};{function class;";var r=/[;{}]/u;function f(){return s+r}\n';
    expect(evaluate(render(tricky))).toBe(tricky);
  });
});
