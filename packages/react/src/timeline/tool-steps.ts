/** Every tool leaf name that has a built-in step (for completeness checks). */
export const BUILT_IN_TOOL_STEP_NAMES: readonly string[] = Object.keys(BUILT_IN_TOOL_STEPS);

/** The plain step a built-in tool reads as, by leaf name; null for any other tool. */
export function builtInToolStep(leaf: string): ToolStepId | null {
  return Object.hasOwn(BUILT_IN_TOOL_STEPS, leaf) ? BUILT_IN_TOOL_STEPS[leaf]! : null;
}

/** A step's words in the host's catalog: running ("Searching the web") or done ("Searched the web"). */
export function toolStepLabel(t: OpenGeniText, step: ToolStepId, phase: ToolStepPhase): string {
  return t(`timeline.toolStep.${step}.${phase}`);
}

/**
 * The phase a call's status reads in: only a call that finished reads as done.
 * A running, failed or interrupted call keeps the ongoing form, so its chip
 * ("Failed", "Interrupted") finishes the sentence.
 */
export function toolStepPhase(status: string | undefined): ToolStepPhase {
  return status === "complete" ? "done" : "running";
}

/** The plain step name for a built-in tool, by leaf name; null for any other tool. */
export function builtInToolStepLabel(
  t: OpenGeniText,
  leaf: string,
  phase: ToolStepPhase,
): string | null {
  const step = builtInToolStep(leaf);
  return step ? toolStepLabel(t, step, phase) : null;
}
