/** Build settings for the extension target, matching the app's signing team. */
function controlBuildSettings({ bundleIdentifier, control, developmentTeam, debug }) {
  const settings = {
    APPLICATION_EXTENSION_API_ONLY: "YES",
    CLANG_ENABLE_MODULES: "YES",
    CODE_SIGN_STYLE: "Automatic",
    CURRENT_PROJECT_VERSION: "1",
    GENERATE_INFOPLIST_FILE: "NO",
    INFOPLIST_FILE: `${CONTROL_TARGET}/${CONTROL_INFO_PLIST}`,
    IPHONEOS_DEPLOYMENT_TARGET: control.deploymentTarget,
    LD_RUNPATH_SEARCH_PATHS:
      '"$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"',
    PRODUCT_BUNDLE_IDENTIFIER: `"${bundleIdentifier}.${control.bundleIdSuffix}"`,
    PRODUCT_NAME: '"$(TARGET_NAME)"',
    SDKROOT: "iphoneos",
    SKIP_INSTALL: "YES",
    SWIFT_EMIT_LOC_STRINGS: "YES",
    SWIFT_OPTIMIZATION_LEVEL: debug ? '"-Onone"' : '"-O"',
    SWIFT_VERSION: "5.0",
    TARGETED_DEVICE_FAMILY: '"1,2"',
  };
  if (debug) settings.SWIFT_ACTIVE_COMPILATION_CONDITIONS = '"DEBUG $(inherited)"';
  if (developmentTeam) settings.DEVELOPMENT_TEAM = developmentTeam;
  return settings;
}

